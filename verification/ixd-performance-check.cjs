async page => {
  const errors=[];
  page.on('pageerror', e=>errors.push(e.message));
  const assert=(value,message)=>{if(!value)throw Error(message)};
  const viewer=()=>page.evaluate(()=>window.rhine.stats().viewer);
  const waitViewer=()=>page.waitForFunction(()=>window.rhine.stats().viewer?.ready && document.querySelector('.model-viewer')?.dataset.transition==='open');
  const settle=()=>page.waitForTimeout(3200);
  const wakes=async(action,name)=>{const before=await viewer();await action();await page.waitForTimeout(500);assert((await viewer()).renderedFrames>before.renderedFrames,`${name} redraws`)};
  await page.setViewportSize({width:1440,height:900});
  await page.goto('http://127.0.0.1:4173/?scene=archive');
  await page.waitForFunction(()=>window.rhine?.stats().ready&&!document.querySelector('#loading'));
  await page.locator('.read-file').click();
  await page.waitForFunction(()=>window.rhine.stats().decryption.clarity>.99);
  await page.locator('[data-action=model-viewer]').click();
  await waitViewer();await settle();
  let before=await viewer();
  await page.waitForTimeout(1500);
  let after=await viewer();
  assert(after.renderedFrames-before.renderedFrames<=2,'Viewer stops drawing when settled');
  assert(after.reusedFrames>before.reusedFrames,'Viewer reuses static canvas');
  const canvas=page.locator('.model-viewer canvas');
  await wakes(async()=>{await canvas.hover();await page.mouse.wheel(0,-220)},'zoom');
  await wakes(async()=>{await page.mouse.move(680,420);await page.mouse.down();await page.mouse.move(850,485,{steps:12});await page.mouse.up()},'rotate');
  await wakes(async()=>{await page.keyboard.press('ArrowRight')},'pan');
  await wakes(async()=>{await page.keyboard.press('Home')},'reset');
  await page.keyboard.press('ArrowLeft');
  assert(!(await viewer()).resetting,'Input interrupts reset');
  await wakes(()=>page.locator('[data-viewer=explode]').click(),'explode');
  await page.waitForFunction(()=>window.rhine.stats().viewer.spread===1);
  assert(JSON.parse(await page.locator('.model-viewer').getAttribute('data-stats')).spread===1,'Final spread is immediately published');
  await wakes(()=>page.locator('[data-viewer=frosted]').click(),'frosted');
  await page.waitForFunction(()=>window.rhine.stats().viewer.clarity===0);
  await wakes(()=>page.locator('[data-viewer=clear]').click(),'clear');
  await page.waitForFunction(()=>window.rhine.stats().viewer.clarity===1);
  await wakes(()=>page.locator('[data-viewer=assemble]').click(),'assemble');
  await page.waitForFunction(()=>window.rhine.stats().viewer.spread===0);
  await wakes(()=>page.setViewportSize({width:390,height:844}),'portrait resize');
  await page.screenshot({path:'verification/ixd-performance-mobile-viewer.png'});
  await page.setViewportSize({width:1440,height:900});
  await page.locator('[data-viewer=close]').click();
  await page.waitForFunction(()=>!window.rhine.stats().viewer.open);
  assert(!(await viewer()).ready,'Closed model is released');
  await page.locator('.settings-button').click();
  await page.locator('[data-color-theme=dark]').click();
  await page.locator('[data-action=close-modal]').click();
  await page.waitForFunction(()=>!document.querySelector('.terminal-modal'));
  await page.locator('[data-action=model-viewer]').click();
  await waitViewer();await settle();
  await page.screenshot({path:'verification/ixd-performance-dark-viewer.png'});
  before=await viewer();await page.waitForTimeout(1200);after=await viewer();
  assert(after.reusedFrames>before.reusedFrames,'Dark reopened viewer settles');
  await page.locator('[data-viewer=close]').click();
  await page.waitForFunction(()=>!window.rhine.stats().viewer.open);
  await page.locator('.settings-button').click();
  await page.locator('[data-color-theme=light]').click();
  await page.locator('[data-action=close-modal]').click();
  await page.waitForFunction(()=>!document.querySelector('.terminal-modal'));
  assert(errors.length===0,errors.join('\n'));
  return {passed:true,checks:['static reuse','zoom','rotate','pan','reset interruption','explode','frosted/clear','assemble','portrait','release','dark reopen'],errors};
}
